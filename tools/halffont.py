def _parse():
    font, lines = {}, [l for l in _FONT.strip().splitlines()]
    for name, rows in zip(lines[0::2], lines[1::2]):
        ch = eval(name)
        rr = rows.split('|')
        assert len(rr) == H and all(len(r) == W for r in rr), (ch, rr)
        font[ch] = [[1 if c == '#' else 0 for c in r] for r in rr]
    return font


FONT = _parse()


def bigram(pair):
    """12 rows of 12 pixels: two letters at x 0 and 6, rows 1-10."""
    rows = [[0] * 12 for _ in range(12)]
    for k, ch in enumerate(pair):
        g = FONT[ch]
        for y in range(H):
            for x in range(W):
                if g[y][x]:
                    rows[1 + y][k * 6 + x] = 1
    return rows


def encode_glyph(rows):
    """The game's 18-byte form: per row pair, a 24-bit little-endian value, first row in the top 12
    bits, leftmost pixel = bit 11 of its row (the inverse of the font reader)."""
    out = bytearray()
    for k in range(6):
        a = sum(rows[2 * k][x] << (11 - x) for x in range(12))
        b = sum(rows[2 * k + 1][x] << (11 - x) for x in range(12))
        out += (a << 12 | b).to_bytes(3, 'little')
    return bytes(out)


def decode_glyph(data):
    rows = []
    for k in range(6):
        v = int.from_bytes(data[3 * k:3 * k + 3], 'little')
        rows += [v >> 12, v & 0xfff]
    return [[(w >> (11 - x)) & 1 for x in range(12)] for w in rows]


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    if len(argv) == 2 and argv[0] == 'sheet':
        from PIL import Image
        chars = sorted(FONT)
        S, cols = 4, 16
        im = Image.new('L', (cols * 8 * S, ((len(chars) + cols - 1) // cols) * 12 * S), 255)
        for n, ch in enumerate(chars):
            ox, oy = (n % cols) * 8 * S, (n // cols) * 12 * S
            for y in range(H):
                for x in range(W):
                    if FONT[ch][y][x]:
                        for dy in range(S):
                            for dx in range(S):
                                im.putpixel((ox + (x + 1) * S + dx, oy + (y + 1) * S + dy), 0)
        im.save(argv[1])
        print(f'{argv[1]}: {len(chars)} letters')
    else:
        sys.exit(__doc__)


if __name__ == '__main__':
    main()
